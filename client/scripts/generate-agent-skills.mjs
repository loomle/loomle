import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";

const clientRoot = new URL("../", import.meta.url);
const repositoryRoot = new URL("../", clientRoot);
const skillsRoot = new URL("skills/", repositoryRoot);
const entries = await readdir(skillsRoot, { withFileTypes: true });
const skills = [];

for (const entry of entries.sort(compareNames)) {
  if (!entry.isDirectory() || entry.isSymbolicLink()) {
    throw new Error(`skills/ may contain only Skill directories: ${entry.name}.`);
  }
  const skillRoot = new URL(`${entry.name}/`, skillsRoot);
  const skillText = await readNormalized(new URL("SKILL.md", skillRoot));
  const metadata = parseFrontmatter(skillText, `skills/${entry.name}/SKILL.md`);
  if (metadata.name !== entry.name) {
    throw new Error(
      `Skill name ${JSON.stringify(metadata.name)} must match directory ${JSON.stringify(entry.name)}.`,
    );
  }

  const files = [{ path: "SKILL.md", text: skillText }];
  const referencesRoot = new URL("references/", skillRoot);
  try {
    for (const reference of (await readdir(referencesRoot, { withFileTypes: true }))
      .sort(compareNames)) {
      if (!reference.isFile() || reference.isSymbolicLink() || !reference.name.endsWith(".md")) {
        throw new Error(
          `Skill references may contain only Markdown files: ${entry.name}/references/${reference.name}.`,
        );
      }
      files.push({
        path: `references/${reference.name}`,
        text: await readNormalized(new URL(reference.name, referencesRoot)),
      });
    }
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }

  skills.push({ ...metadata, files });
}

if (skills.length === 0) throw new Error("skills/ must contain at least one Agent Skill.");

const source = [
  "// Generated by scripts/generate-agent-skills.mjs. Do not edit directly.",
  "export interface EmbeddedAgentSkillFile { readonly path: string; readonly text: string; }",
  "export interface EmbeddedAgentSkill { readonly name: string; readonly description: string; readonly files: readonly EmbeddedAgentSkillFile[]; }",
  `export const agentSkills: readonly EmbeddedAgentSkill[] = ${JSON.stringify(skills, null, 2)};`,
].join("\n\n") + "\n";

const output = new URL("src/generated/agent-skills.ts", clientRoot);
await mkdir(new URL("src/generated/", clientRoot), { recursive: true });
await writeFile(output, source, "utf8");

function parseFrontmatter(text, path) {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!match) throw new Error(`${path} must begin with YAML frontmatter.`);
  const fields = new Map();
  for (const line of match[1].split("\n")) {
    const field = /^([a-z][a-z0-9-]*):\s*(.+)$/.exec(line);
    if (!field) throw new Error(`${path} has unsupported frontmatter line: ${line}.`);
    if (fields.has(field[1])) throw new Error(`${path} repeats frontmatter field ${field[1]}.`);
    fields.set(field[1], field[2].trim());
  }
  const name = fields.get("name");
  const description = fields.get("description");
  if (fields.size !== 2 || !name || !description) {
    throw new Error(`${path} frontmatter must contain exactly name and description.`);
  }
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name) || name.length > 64) {
    throw new Error(`${path} has an invalid Agent Skill name.`);
  }
  if (description.length > 1024) throw new Error(`${path} description exceeds 1024 characters.`);
  return { name, description };
}

async function readNormalized(url) {
  const text = (await readFile(url, "utf8")).replace(/\r\n?/g, "\n");
  if (!text.endsWith("\n")) throw new Error(`${url.pathname} must end with a newline.`);
  return text;
}

function compareNames(left, right) {
  return left.name < right.name ? -1 : left.name > right.name ? 1 : 0;
}
